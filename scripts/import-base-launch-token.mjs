import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

export function writeLaunchTokenArtifact(artifact) {
  const constructor = artifact.abi?.find(entry => entry.type === 'constructor');
  if (constructor?.inputs.map(input => input.type).join(',') !== 'string,string,uint256,address')
    throw new Error('LaunchToken constructor must receive name, symbol, raw supply and recipient.');
  for (const field of ['bytecode', 'deployedBytecode']) {
    const value = artifact[field];
    if (!value || !/^0x(?:[0-9a-f]{2})+$/i.test(value.object) || Object.keys(value.linkReferences ?? {}).length || Object.keys(value.immutableReferences ?? {}).length)
      throw new Error(`LaunchToken ${field}.object must be fully linked bytecode without immutable patches.`);
  }
  fs.writeFileSync('src/lib/base/abi/LaunchToken.json', JSON.stringify(artifact, null, 2) + '\n');
  const deployment = { abi: artifact.abi, bytecode: artifact.bytecode.object, deployedBytecode: artifact.deployedBytecode.object };
  fs.writeFileSync('src/lib/base/tokenDeployment.ts', '// Generated by scripts/import-base-launch-token.mjs. Creation uses bytecode.object; runtime verification uses deployedBytecode.object.\nexport const launchTokenDeployment = ' + JSON.stringify(deployment, null, 2) + ' as const;\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  if (!process.argv[2]) throw new Error('Usage: node scripts/import-base-launch-token.mjs <LaunchToken.json>');
  writeLaunchTokenArtifact(JSON.parse(fs.readFileSync(process.argv[2], 'utf8')));
}
